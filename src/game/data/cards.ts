import type { Card, CardEffects } from '../types/cards';
import type { CardCategory, ServiceId } from '../types/common';

/**
 * CATÁLOGO DE MEDIDAS
 *
 * Sessenta cartas escritas como dados. Cada uma é um objeto independente: mudar
 * chance, custo ou efeito é editar uma linha, sem tocar em engine nenhum.
 *
 * `defineCard` só traduz a forma compacta de escrever (`chance`, `cost`,
 * `services`…) para o objeto completo e explícito que os engines consomem.
 */

interface CardSeed {
  n: number;
  title: string;
  description: string;
  category: CardCategory;
  /** Chance de sucesso, em %. */
  chance: number;
  /** Custo de implementação, em reais. */
  cost: number;
  /** Variação recorrente da arrecadação mensal, em reais. */
  tax?: number;
  /** Variação recorrente dos gastos mensais, em reais. */
  expense?: number;
  /** A variação recorrente vale mesmo no fracasso. */
  keepRecurringOnFailure?: boolean;
  services?: Card['serviceEffects'];
  resources?: Card['resourceEffects'];
  international?: Card['internationalEffects'];
  social?: Card['socialEffects'];
  oneOfServices?: Partial<Record<ServiceId, number>>[];
  /** O que a medida constrói. Presente = é uma obra. */
  structure?: string;
  failure?: CardEffects;
}

function defineCard(seed: CardSeed): Card {
  return {
    id: `carta-${String(seed.n).padStart(2, '0')}`,
    number: seed.n,
    title: seed.title,
    description: seed.description,
    category: seed.category,
    probability: seed.chance,
    implementationCost: seed.cost,
    recurringTaxChange: seed.tax ?? 0,
    recurringExpenseChange: seed.expense ?? 0,
    recurringAppliesOnFailure: seed.keepRecurringOnFailure ?? false,
    serviceEffects: seed.services ?? {},
    resourceEffects: seed.resources ?? {},
    internationalEffects: seed.international ?? {},
    socialEffects: seed.social ?? {},
    ...(seed.oneOfServices ? { randomServiceEffects: seed.oneOfServices } : {}),
    createsStructure: seed.structure !== undefined,
    ...(seed.structure !== undefined ? { structureLabel: seed.structure } : {}),
    ...(seed.failure ? { failureEffects: seed.failure } : {}),
  };
}

